const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { outputRoot, loadPlaywright, browserLaunchOptions } = require('./test-env.cjs');
const url = new URL(process.env.HL_PREVIEW_URL || process.argv[2] || 'http://127.0.0.1:1430/');
assert(['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname));
url.searchParams.set('preview', '1');
const report = { fixtureOnly: true, checks: [], errors: [] };
const check = name => { report.checks.push(name); console.log(`PASS ${name}`); };
const prevented = (locator, point = { x: 100, y: 100 }) => locator.evaluate((element, point) => {
  const event = new MouseEvent('contextmenu', { bubbles: true, cancelable: true, clientX: point.x, clientY: point.y, button: 2 });
  const dispatched = element.dispatchEvent(event);
  return event.defaultPrevented && !dispatched;
}, point);

(async () => {
  fs.mkdirSync(outputRoot, { recursive: true });
  const browser = await loadPlaywright().chromium.launch(browserLaunchOptions);
  try {
    const context = await browser.newContext({ viewport: { width: 960, height: 640 }, locale: 'ru-RU', reducedMotion: 'reduce' });
    await context.addInitScript(() => {
      localStorage.setItem('humble-library-language', 'ru');
      window.__copiedPreview = [];
      Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { window.__copiedPreview.push(text); } } });
    });
    const page = await context.newPage();
    page.on('pageerror', error => report.errors.push(error.message));
    await page.goto(url.toString());
    await page.locator('.bundle-tile').first().waitFor();
    for (const selector of ['h1', '.bundle-tile', '.search input']) assert(await prevented(page.locator(selector).first()), `Default context menu prevented: ${selector}`);
    assert.equal(await page.getByRole('menu').count(), 0);
    assert.equal(await page.locator('h1').evaluate(element => getComputedStyle(element).userSelect), 'none');
    assert.equal(await page.locator('.bundle-tile').first().evaluate(element => getComputedStyle(element).userSelect), 'none');
    const search = page.locator('.search input');
    assert.equal(await search.evaluate(element => getComputedStyle(element).userSelect), 'text');
    await search.fill('Game'); await search.press('Control+A');
    assert.deepEqual(await search.evaluate(element => [element.selectionStart, element.selectionEnd]), [0, 4]);
    await search.fill('');
    check('Default menus are suppressed on headings, tiles and inputs; static selection is disabled and input selection remains editable');
    await page.locator('.bundle-tile').first().click();
    const code = page.locator('.key-value').first(), cell = code.locator('..');
    assert.equal(await code.evaluate(element => getComputedStyle(element).userSelect), 'none');
    const hidden = page.locator('.key-table tbody tr').filter({ hasText: 'Adventure Toolkit' }).locator('td').nth(2);
    assert(await prevented(hidden));
    assert.equal(await page.getByRole('menu').count(), 0, 'Unrevealed keys have no custom copy action');
    await code.click({ button: 'right' });
    const menu = page.getByRole('menu', { name: 'Скопировать ключ', exact: true });
    await menu.waitFor();
    assert.equal(await menu.getByRole('menuitem').count(), 1);
    assert.equal(await menu.getByRole('menuitem').innerText(), 'Скопировать ключ');
    await menu.getByRole('menuitem').click();
    assert.deepEqual(await page.evaluate(() => window.__copiedPreview), ['PREVIEW-FAB-ONLY-0001']);
    await menu.waitFor({ state: 'hidden' });
    assert.equal(await menu.count(), 0);
    check('Only revealed keys have a one-action custom menu; right-click copy sends the exact captured key');
    await code.focus(); await code.press('Shift+F10'); await menu.waitFor();
    await page.keyboard.press('Escape');
    await menu.waitFor({ state: 'hidden' });
    assert.equal(await menu.count(), 0);
    assert.equal(await code.evaluate(element => document.activeElement === element), true);
    await code.press('ContextMenu'); await menu.waitFor();
    await menu.getByRole('menuitem').press('Enter');
    await menu.waitFor({ state: 'hidden' });
    assert.deepEqual(await page.evaluate(() => window.__copiedPreview), ['PREVIEW-FAB-ONLY-0001', 'PREVIEW-FAB-ONLY-0001']);
    check('Shift+F10, ContextMenu, Enter and Escape work with focus returned to the originating key');
    assert(await prevented(cell, { x: 955, y: 635 }));
    await menu.waitFor();
    const box = await menu.boundingBox();
    assert(box && box.x >= 0 && box.y >= 0 && box.x + box.width <= 960 && box.y + box.height <= 640, 'Custom menu is clamped to the viewport');
    await page.screenshot({ path: path.join(outputRoot, 'key-context-menu-960x640.png') });
    await page.locator('h1').click();
    await menu.waitFor({ state: 'hidden' });
    assert.equal(await menu.count(), 0);
    await code.click({ button: 'right' }); await menu.waitFor();
    await page.locator('.workspace-content').evaluate(element => { element.dispatchEvent(new Event('scroll')); });
    await menu.waitFor({ state: 'hidden' });
    assert.equal(await menu.count(), 0);
    await code.click({ button: 'right' }); await menu.waitFor();
    await page.setViewportSize({ width: 1000, height: 650 });
    await menu.waitFor({ state: 'hidden' });
    check('Key-cell whitespace opens the same menu; viewport clamp, outside click, scroll and resize dismissal work');
    assert.deepEqual(report.errors, []);
    await context.close();
  } finally {
    await browser.close();
    fs.writeFileSync(path.join(outputRoot, 'context-menu-report.json'), JSON.stringify(report, null, 2));
  }
  console.log(`PASS ${report.checks.length} context-menu scenarios`);
})().catch(error => { console.error(error); process.exitCode = 1; });
